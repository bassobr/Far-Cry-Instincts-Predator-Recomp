"""Converts Xenia's generated PPC opcode lookup (src/xenia/cpu/ppc/ppc_opcode_lookup_gen.cc, BSD 3-Clause,
Copyright Ben Vanik) into tests/semantics/py/xenia_lookup.py.

The reference interpreter decodes with Xenia's table instead of the binutils derived decoder of our codegen,
so a decoder error in either one shows up as a mismatch (forms.py records the codegen's mnemonic per word).

  python convert_xenia_lookup.py <ppc_opcode_lookup_gen.cc> <out.py>
"""
import re
import sys

HEADER = '''# Generated by convert_xenia_lookup.py from Xenia (xenia-canary, src/xenia/cpu/ppc/ppc_opcode_lookup_gen.cc).
# Xenia : Xbox 360 Emulator Research Project. Copyright Ben Vanik. BSD 3-Clause License
# (https://github.com/xenia-canary/xenia-canary/blob/canary_experimental/LICENSE). Do not edit.


def _x(v, a, b):
    return (v >> (32 - 1 - b)) & ((1 << (b - a + 1)) - 1)


def lookup(code):
'''


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    body = src[src.index("PPCOpcode LookupOpcode(uint32_t code) {"):]
    lines = body.splitlines()[1:]
    out = [HEADER]
    depth = 0          # switch nesting
    indent = 1
    pending_case = False
    stack = []
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        line = line.replace("ExtractBits(code,", "_x(code,")
        m = re.match(r"switch \((.*)\) \{$", line)
        if m:
            var = "s%d" % depth
            out.append("    " * indent + "%s = %s\n" % (var, m.group(1)))
            stack.append((var, indent))
            depth += 1
            continue
        m = re.match(r"case (0b[01]+|\d+): PPC_DECODER_HIT\((\w+)\);$", line)
        if m:
            var, ind = stack[-1]
            out.append("    " * ind + "if %s == %s:\n" % (var, m.group(1)))
            out.append("    " * (ind + 1) + "return %r\n" % m.group(2))
            continue
        m = re.match(r"case (0b[01]+|\d+):$", line)
        if m:
            var, ind = stack[-1]
            out.append("    " * ind + "if %s == %s:\n" % (var, m.group(1)))
            indent = ind + 1
            continue
        if line in ("PPC_DECODER_MISS;", "default: PPC_DECODER_MISS;"):
            out.append("    " * indent + "return None\n")
            # a miss closes the enclosing case block
            if stack:
                indent = stack[-1][1]
            continue
        if line == "}":
            if stack:
                var, ind = stack.pop()
                depth -= 1
                indent = ind
                if not stack:
                    break
            continue
        if line.startswith("//") or line.startswith("#"):
            continue
        raise SystemExit("unexpected line: %r" % raw)
    out.append("    return None\n")
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("".join(out))


if __name__ == "__main__":
    main()
