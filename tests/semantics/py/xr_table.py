"""Entry point table for the XenonRecomp build of the semantic test runner.

XenonRecomp's test mode (XenonRecomp.exe <dir with .o> <out>) writes <stem>.cpp with one
PPC_FUNC_IMPL(__imp__<stem>_<ADDR>) per function it found.

  python xr_table.py <xr_out_dir> <stem> <out.cpp>
"""
import os
import re
import sys


def main():
    out_dir, stem, out = sys.argv[1:4]
    text = open(os.path.join(out_dir, stem + ".cpp"), encoding="utf-8").read()
    names = sorted(set(re.findall(r"PPC_FUNC_IMPL\(__imp__(%s_([0-9A-F]+))\)" % re.escape(stem), text)))
    lines = ["// Generated by xr_table.py. DO NOT EDIT.", "#define PPC_CONFIG_H_INCLUDED", "#include <ppc_context.h>",
             '#include "sem_runner_api.h"', ""]
    for name, _ in names:
        lines.append("extern \"C\" PPC_FUNC(__imp__%s);" % name)
    lines.append('extern "C" const FcpSemFunc fcp_sem_funcs[] = {')
    for name, addr in names:
        lines.append("  {0x%su, &__imp__%s}," % (addr, name))
    lines += ["  {0u, nullptr}", "};", ""]
    new = "\n".join(lines)
    if not os.path.exists(out) or open(out, encoding="utf-8").read() != new:
        open(out, "w", encoding="utf-8").write(new)
    print("xr_table.py: %d functions" % len(names))


if __name__ == "__main__":
    main()
