"""Generates a codegen configuration [function_names] from config/predator/d3d_symbols.toml.

This makes the D3D names symbols of the generated code (D3DDevice_Swap instead of sub_<address>), and the
hooks in src/ refer to names only. Addresses live in the configuration only.
"D3D::Name" becomes "D3D_Name" (C identifier). Duplicate names or addresses abort.

  python -I tools/boot/gen_d3d_names.py <d3d_symbols.toml> <output.toml> [<output.h>]

The optional header holds the values from [library] that are not addresses (device size).

Writes only when the content changed (Ninja: restat).
"""

import re
import sys
import tomllib
from pathlib import Path

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def main() -> int:
    if len(sys.argv) not in (3, 4):
        print(__doc__)
        return 2
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    data = tomllib.loads(src.read_text(encoding="utf-8"))
    names: dict[int, str] = {}
    seen: dict[str, int] = {}
    for entry in data.get("function", []):
        addr = int(entry["address"])
        name = str(entry["name"]).replace("::", "_")
        if not IDENT.match(name):
            print(f"gen_d3d_names: invalid name {entry['name']!r} at 0x{addr:08X}")
            return 1
        if addr in names or name in seen:
            print(f"gen_d3d_names: duplicate: {name} 0x{addr:08X}")
            return 1
        names[addr] = name
        seen[name] = addr
    lines = [
        "# Generated by tools/boot/gen_d3d_names.py from config/predator/d3d_symbols.toml. Do not edit.",
        f"# {len(names)} names of the D3D9 library (confidence: see the source).",
        "[function_names]",
    ]
    lines += [f'0x{a:08X} = "{n}"' for a, n in sorted(names.items())]
    write_if_changed(dst, "\n".join(lines) + "\n")
    if len(sys.argv) == 4:
        lib = data.get("library", {})
        header = [
            "// Generated by tools/boot/gen_d3d_names.py from config/predator/d3d_symbols.toml [library].",
            "#pragma once",
            "#include <cstdint>",
            "namespace fcp::d3d {",
            f"inline constexpr uint32_t kDeviceSize = {int(lib.get('device_size', 0))};",
            "}  // namespace fcp::d3d",
        ]
        write_if_changed(Path(sys.argv[3]), "\n".join(header) + "\n")
    return 0


def write_if_changed(path: Path, text: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_d3d_names: {path} written")


if __name__ == "__main__":
    sys.exit(main())
