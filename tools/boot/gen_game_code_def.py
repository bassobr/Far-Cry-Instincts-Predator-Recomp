"""Writes predator_code_delay.def: the originals `__imp__<name>` that predator.exe can import from predator_code.dll
(delay-loaded: the DLL is built on the player's first start).

Names: [function_names] of the title configuration (config/predator/default.toml, generated/d3d_names.toml). The EXE
takes only what its code really calls (the linker pulls only used entries from the import library); the DLL exports
exactly the names of the EXE's delay import table (src/fcp/game_code_build.cpp). No addresses, nothing of the
game: only the names from the configuration.

  python -I tools/boot/gen_game_code_def.py <output.def> <names.toml> [<names.toml> ...]

Writes only when the content changed.
"""

import re
import sys
from pathlib import Path

RE_NAME = re.compile(r'^\s*0x[0-9A-Fa-f]+\s*=\s*"([A-Za-z_][A-Za-z0-9_]*)"', re.M)


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    dst = Path(sys.argv[1])
    names: set[str] = set()
    for f in sys.argv[2:]:
        names.update(RE_NAME.findall(Path(f).read_text(encoding="utf-8", errors="replace")))
    if not names:
        print("gen_game_code_def: no names found")
        return 1
    lines = ["; Generated by tools/boot/gen_game_code_def.py. Do not edit.", "LIBRARY predator_code.dll", "EXPORTS"]
    lines += [f"  __imp__{n}" for n in sorted(names)]
    text = "\n".join(lines) + "\n"
    if dst.exists() and dst.read_text(encoding="utf-8") == text:
        return 0
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_game_code_def: {len(names)} names to {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
