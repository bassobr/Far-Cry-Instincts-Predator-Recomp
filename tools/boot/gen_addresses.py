"""Generates fcp_addresses.h from config/predator/runtime_addresses.toml (data addresses of the runtime layer).

  python -I tools/boot/gen_addresses.py <runtime_addresses.toml> <fcp_addresses.h>

Writes only when the content changed.
"""

import sys
import tomllib
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    data = tomllib.loads(src.read_text(encoding="utf-8"))
    out = [
        f"// Generated by tools/boot/gen_addresses.py from {src.name}. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "namespace fcp::addr {",
    ]
    for name, value in data.items():
        if not isinstance(value, int) or not name.isidentifier():
            print(f"gen_addresses: {name} is not an address")
            return 1
        out.append(f"constexpr uint32_t {name} = 0x{value:08X};")
    out += ["}  // namespace fcp::addr", ""]
    text = "\n".join(out)
    if dst.exists() and dst.read_text(encoding="utf-8") == text:
        return 0
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
