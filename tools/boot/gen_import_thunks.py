"""Generates the import wrappers for the import trace (src/fcp/imports.h).

The generated code calls every kernel/XAM import as a symbol `__imp__<name>` that rexkernel.dll exports.
predator.exe defines these symbols itself and exports them (predator_code.dll links them from the EXE's import
library), counts the call and calls the SDK function through GetProcAddress. Since the game code moved into
predator_code.dll the list no longer depends on the game: wrappers for every `__imp__` export of the rexkernel
import library (llvm-nm), not only for the game's imports. Which of them the game imports, the EXE reads at run
time from the DLL's import table (fcp::imports::MarkImported).
Stub marking: exports the SDK defines with REX_EXPORT_STUB/REX_EXPORT_STUB_RETURN. Module from the export tables.

  python -I tools/boot/gen_import_thunks.py <llvm-nm.exe> <rexkernel.lib> <rexglue/src> <output.cpp>
         [<names.toml> ...]

Excluded are the names from [function_names] of the title configuration (names.toml: default.toml,
d3d_names.toml): rexkernel exports its own `__imp__` symbols for 34 of them (e.g. XMemAlloc, D3DDevice_SetTexture),
but in the game these are guest functions whose original `__imp__<name>` comes from predator_code.dll.

Writes only when the content changed.
"""

import re
import subprocess
import sys
from pathlib import Path

RE_NM = re.compile(r"\b__imp___imp__([A-Za-z_][A-Za-z0-9_]*)\b")
RE_NAME = re.compile(r'^\s*0x[0-9A-Fa-f]+\s*=\s*"([A-Za-z_][A-Za-z0-9_]*)"', re.M)
RE_STUB = re.compile(r"REX_EXPORT_STUB(?:_RETURN)?\(\s*__imp__([A-Za-z_][A-Za-z0-9_]*)")
RE_TABLE = re.compile(r"REX_EXPORT\(\s*(\w+)\s*,\s*0x[0-9A-Fa-f]+\s*,\s*(\w+)\s*,\s*(kFunction|kVariable)")


def main() -> int:
    if len(sys.argv) < 5:
        print(__doc__)
        return 2
    nm, kernel_lib, sdk_src, dst = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3]), Path(sys.argv[4])
    game_names: set[str] = set()
    for names_file in sys.argv[5:]:
        game_names.update(RE_NAME.findall(Path(names_file).read_text(encoding="utf-8", errors="replace")))
    listing = subprocess.run([nm, str(kernel_lib)], capture_output=True, text=True, check=True).stdout
    imports = sorted(set(RE_NM.findall(listing)) - game_names)
    stubs: set[str] = set()
    module_of: dict[str, str] = {}
    for path in sdk_src.rglob("*"):
        if path.suffix not in (".cpp", ".inc", ".h"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        stubs.update(RE_STUB.findall(text))
        if path.name == "export_table.inc":
            for module, name, _kind in RE_TABLE.findall(text):
                module_of.setdefault(name, module)
    if not imports:
        print(f"gen_import_thunks: no __imp__ exports in {kernel_lib}")
        return 1
    out = [
        "// Generated by tools/boot/gen_import_thunks.py from the exports of rexkernel. Do not edit.",
        "// Holds no guest addresses and nothing of the game: only names of the SDK's kernel/XAM exports.",
        '#include "fcp/imports.h"',
        "#include <rex/ppc/recompiled_code.h>",
        "",
        "namespace fcp::imports {",
        "const Entry kTable[] = {",
    ]
    for name in imports:
        kind = "Kind::kStub" if name in stubs else "Kind::kImplemented"
        out.append(f'    {{"{name}", "{module_of.get(name, "?")}", {kind}}},')
    out += ["};", f"const size_t kCount = {len(imports)};", "}  // namespace fcp::imports", ""]
    for i, name in enumerate(imports):
        out += [
            f"extern \"C\" __declspec(dllexport) REX_FUNC(__imp__{name}) {{",
            f"  static PPCFunc* const real = ::fcp::imports::Resolve({i});",
            f"  const bool describe = ::fcp::imports::Enter({i}, ctx, base);",
            "  real(ctx, base);",
            f"  if (describe) ::fcp::imports::Leave({i}, ctx, base);",
            "}",
        ]
    text = "\n".join(out) + "\n"
    if dst.exists() and dst.read_text(encoding="utf-8") == text:
        return 0
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(text, encoding="utf-8", newline="\n")
    n_stub = sum(1 for n in imports if n in stubs)
    print(f"gen_import_thunks: {len(imports)} exports ({n_stub} stubs) to {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
